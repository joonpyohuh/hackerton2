"""SQLite store populated from the existing 50k-row data.js analysis artifact.

The source is NOT raw behavior/payment rows: precomputed flags come from build_data.py.
A snapshot is immutable; active pointer is updated only after a successful import.
"""
import hashlib
import json
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from . import settings

VOUCHER_BIT = 1 << 2
DDL = """
PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS snapshots (
 id TEXT PRIMARY KEY, imported_at TEXT NOT NULL, source_hash TEXT NOT NULL UNIQUE,
 base_date TEXT NOT NULL, customer_count INTEGER NOT NULL, dictionaries_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS app_state (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS customers (
 snapshot_id TEXT NOT NULL, user_key TEXT NOT NULL, signup_day INTEGER NOT NULL,
 device INTEGER NOT NULL, age INTEGER NOT NULL, gender INTEGER NOT NULL,
 push INTEGER NOT NULL, behavior_mask INTEGER NOT NULL, first_payment_day INTEGER NOT NULL,
 activated7 INTEGER NOT NULL, activated14 INTEGER NOT NULL, activated28 INTEGER NOT NULL,
 retained INTEGER NOT NULL, channel_mask INTEGER NOT NULL, product INTEGER NOT NULL,
 genre INTEGER NOT NULL, auto_payment INTEGER NOT NULL,
 PRIMARY KEY(snapshot_id, user_key), FOREIGN KEY(snapshot_id) REFERENCES snapshots(id));
CREATE INDEX IF NOT EXISTS ix_customer_filter ON customers(snapshot_id,signup_day,device,age,gender,push);
CREATE TABLE IF NOT EXISTS recommendations (
 id INTEGER PRIMARY KEY AUTOINCREMENT, created_at TEXT NOT NULL,
 snapshot_id TEXT NOT NULL, target_id TEXT NOT NULL, filters_json TEXT NOT NULL,
 summary_json TEXT NOT NULL, result_json TEXT NOT NULL, model TEXT NOT NULL,
 FOREIGN KEY(snapshot_id) REFERENCES snapshots(id));
"""
COLUMNS = ('signup_day','device','age','gender','push','behavior_mask','first_payment_day',
           'activated7','activated14','activated28','retained','channel_mask','product','genre','auto_payment')
SRC_COLS = ('sd','dev','age','gen','push','bm','fp','a7','a14','a28','ret','ch','prod','tg','auto')

def connect():
    settings.DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    c = sqlite3.connect(str(settings.DB_PATH), timeout=25)
    c.row_factory = sqlite3.Row
    c.execute('PRAGMA foreign_keys=ON')
    c.execute('PRAGMA busy_timeout=25000')
    c.executescript(DDL)
    return c

def load_source(path: Path):
    raw = path.read_bytes()
    # input generated by build_data.py; JSON is parsed, never executed
    text = raw.decode('utf-8').strip()
    prefix = 'window.DATA='
    if not text.startswith(prefix):
        raise ValueError('data.js must start with window.DATA=')
    obj = json.loads(text[len(prefix):].removesuffix(';'))
    cols = obj['cols']; keys = obj['keys']; n = len(keys)
    if n < 1 or any(len(cols[k]) != n for k in SRC_COLS):
        raise ValueError('Source feature column lengths do not agree')
    if len(set(keys)) != n: raise ValueError('Duplicate user_key in data.js')
    return obj, hashlib.sha256(raw).hexdigest()

def import_snapshot(c, path=None):
    obj, digest = load_source(Path(path or settings.DATA_PATH))
    existing = c.execute('SELECT id FROM snapshots WHERE source_hash=?', (digest,)).fetchone()
    if existing:
        c.execute('INSERT INTO app_state(key,value) VALUES (?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value', ('active_snapshot',existing['id']))
        c.commit(); return {'snapshot_id': existing['id'], 'customer_count':len(obj['keys']), 'changed':False}
    snapshot_id = 's_' + digest[:16]
    cols = obj['cols']
    meta = {k: obj[k] for k in ('behaviors','devices','ages','products','genres','reco','payWindow') if k in obj}
    now = datetime.now(timezone.utc).isoformat()
    try:
        c.execute('BEGIN IMMEDIATE')
        c.execute('INSERT INTO snapshots VALUES (?,?,?,?,?,?)', (snapshot_id,now,digest,obj['base'],len(obj['keys']),json.dumps(meta,ensure_ascii=False)))
        rows = ((snapshot_id,str(key),*(int(cols[k][i]) for k in SRC_COLS)) for i,key in enumerate(obj['keys']))
        c.executemany('INSERT INTO customers VALUES ('+','.join(['?']*17)+')', rows)
        c.execute('INSERT INTO app_state(key,value) VALUES (?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value', ('active_snapshot',snapshot_id))
        c.commit()
    except Exception:
        c.rollback(); raise
    return {'snapshot_id':snapshot_id,'customer_count':len(obj['keys']),'changed':True}

def active(c):
    r=c.execute("SELECT s.* FROM snapshots s JOIN app_state a ON a.value=s.id WHERE a.key='active_snapshot'").fetchone()
    if not r: raise RuntimeError('No active data snapshot: run python -m backend.import_snapshot')
    return dict(r)

def initialize():
    with connect() as c:
        try: active(c)
        except RuntimeError:
            if settings.DATA_PATH.exists(): import_snapshot(c)
